function productSchema(product, canonical) {
  const common = {
    "@context": "https://schema.org",
    "@type": product.priceMinor == null ? "Service" : "Product",
    name: product.name,
    description: product.summary,
    image: product.gallery.map((image) => absolute(`assets/images/${image}`)),
    category: catalog.categories[product.category].name,
    url: canonical,
    provider: { "@type": "Organization", name: "Digital X", url: catalog.origin },
  };
  if (product.priceMinor != null) {
    common.offers = {
      "@type": "Offer",
      price: (product.priceMinor / 100).toFixed(2),
      priceCurrency: "BAM",
      availability: "https://schema.org/InStock",
      url: canonical,
    };
  }
  return common;
}

