const exactLegacyRedirects = [
  ...catalog.products.map((product) => ({
    source: "/shop/product.html",
    has: [{ type: "query", key: "id", value: product.id }],
    destination: `/${catalog.productPath(product.id)}`,
    permanent: true,
  })),
  ...categoryEntries.map(([id]) => ({
    source: "/shop/category.html",
    has: [{ type: "query", key: "category", value: id }],
    destination: `/${catalog.categoryPath(id)}`,
    permanent: true,
  })),
];
